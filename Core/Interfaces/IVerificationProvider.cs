using Netka.Identity.Core.Models;

namespace Netka.Identity.Core.Interfaces;

/// <summary>
/// Defines the contract for identity verification providers (ThaID, Google, Microsoft, etc.).
/// </summary>
public interface IVerificationProvider
{
    /// <summary>
    /// Gets the unique identifier for this provider (e.g., "ThaID", "Google", "Microsoft").
    /// </summary>
    string ProviderName { get; }

    /// <summary>
    /// Generates the OAuth 2.0 / OIDC authorization URL for redirecting the user.
    /// </summary>
    /// <param name="redirectUri">The callback URI registered with the provider.</param>
    /// <param name="state">Cryptographic CSRF state token generated by the caller.</param>
    /// <returns>The full authorization URL.</returns>
    string GetAuthorizationUrl(string redirectUri, string state);

    /// <summary>
    /// Verifies user identity by exchanging the authorization code and retrieving user information.
    /// </summary>
    /// <param name="request">The verification request containing the authorization code and parameters.</param>
    /// <param name="cancellationToken">Cancellation token for async operations.</param>
    /// <returns>A <see cref="VerificationResult"/> containing verified user attributes or error details.</returns>
    Task<VerificationResult> VerifyAsync(VerificationRequest request, CancellationToken cancellationToken = default);
}

namespace Netka.Identity.Core.Interfaces;

/// <summary>
/// Cryptographic trust anchor service validating sovereign Country Signing CA (CSCA) certificates,
/// ICAO Public Key Directory (PKD) MasterLists, and chip Active Authentication challenges.
/// </summary>
public interface ISovereignTrustAnchorService
{
    /// <summary>
    /// Performs Passive Authentication (PA) by verifying the digital signature of the Security Object Document (EF.SOD)
    /// against the issuing nation's sovereign CSCA root certificate, and confirming all Data Group SHA-256 hashes.
    /// </summary>
    /// <param name="sodBytes">Binary content of EF.SOD.</param>
    /// <param name="dataGroupHashes">Dictionary of Data Group identifiers (e.g. 1 for DG1, 2 for DG2) and their corresponding binary payloads.</param>
    /// <param name="countryCode">Three-letter ISO 3166-1 alpha-3 country code.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>True if the sovereign government signature is valid and no Data Groups were tampered with.</returns>
    Task<bool> VerifyPassiveAuthenticationAsync(
        byte[] sodBytes, 
        IDictionary<int, byte[]> dataGroupHashes, 
        string countryCode, 
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Performs Active Authentication (AA) to verify that the physical chip contains the authentic sovereign private key
    /// and is not an unauthorized cloned hardware emulator.
    /// </summary>
    /// <param name="challengeNonce">Random 8-byte or 16-byte nonce challenge generated by the terminal reader.</param>
    /// <param name="chipSignature">The cryptographic signature returned by the chip (ECDSA / RSA).</param>
    /// <param name="chipPublicKeyBytes">The chip's public key extracted from Data Group 15 (DG15).</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>True if the chip successfully proved possession of the sovereign private key.</returns>
    Task<bool> VerifyActiveAuthenticationAsync(
        byte[] challengeNonce, 
        byte[] chipSignature, 
        byte[]? chipPublicKeyBytes = null, 
        CancellationToken cancellationToken = default);
}

using Netka.Identity.Core.Models;

namespace Netka.Identity.Core.Interfaces;

/// <summary>
/// Defines the contract for DOPA ThaID (OAuth 2.0 / OIDC) operations.
/// Each method corresponds directly to an official ThaID endpoint and returns the provider response unmodified.
/// </summary>
public interface IThaIdProvider : IVerificationProvider
{
    /// <summary>
    /// Generates the ThaID OAuth 2.0 authorization URL for redirecting the user or rendering a QR Code.
    /// </summary>
    /// <param name="redirectUri">Callback URI registered with DOPA ThaID.</param>
    /// <param name="state">CSRF state token generated by the caller.</param>
    /// <returns>The full ThaID authorization URL.</returns>
    string GetAuthorizationUrl(string redirectUri, string state);

    /// <summary>
    /// Generates the ThaID OAuth 2.0 authorization URL (with optional PKCE, OIDC nonce, and custom scope parameters).
    /// </summary>
    /// <param name="redirectUri">Callback URI registered with DOPA ThaID.</param>
    /// <param name="state">CSRF state token generated by the caller.</param>
    /// <param name="codeChallenge">Optional PKCE code challenge (S256 Base64Url string).</param>
    /// <param name="codeChallengeMethod">PKCE challenge method (defaults to "S256").</param>
    /// <param name="nonce">Optional OIDC nonce parameter.</param>
    /// <param name="scope">Optional OAuth 2.0 scope parameter. If omitted, uses configured <see cref="ThaIdOptions.Scope"/> or defaults to <c>"openid pid profile"</c>.</param>
    /// <returns>The full ThaID authorization URL.</returns>
    string GetAuthorizationUrl(
        string redirectUri,
        string state,
        string? codeChallenge,
        string codeChallengeMethod = "S256",
        string? nonce = null,
        string? scope = null);

    /// <summary>
    /// Exchanges an OAuth 2.0 authorization code for tokens at the ThaID Token Endpoint (<c>/api/v2/oauth2/token/</c>).
    /// </summary>
    /// <param name="authorizationCode">The authorization code received from the ThaID callback.</param>
    /// <param name="redirectUri">Optional redirect URI (uses configured RedirectUri if omitted).</param>
    /// <param name="codeVerifier">Optional PKCE code verifier if PKCE was used during authorization.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>A <see cref="VerificationResult"/> containing the raw token and identity response from ThaID.</returns>
    Task<VerificationResult> ExchangeCodeAsync(
        string authorizationCode,
        string? redirectUri = null,
        string? codeVerifier = null,
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Requests a new access token using a refresh token at the ThaID Token Endpoint (<c>/api/v2/oauth2/token/</c>).
    /// </summary>
    /// <param name="refreshToken">The refresh token previously issued by ThaID.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>A <see cref="VerificationResult"/> containing the new token response from ThaID.</returns>
    Task<VerificationResult> RefreshTokenAsync(
        string refreshToken,
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Inspects an access token to verify its active status at the ThaID Token Introspect Endpoint (<c>/api/v2/oauth2/introspect/</c>).
    /// </summary>
    /// <param name="accessToken">The access token to inspect.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>A <see cref="VerificationResult"/> containing the token inspection metadata (<c>active</c>, <c>sub</c>, <c>exp</c>, <c>scope</c>).</returns>
    Task<VerificationResult> InspectTokenAsync(
        string accessToken,
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Revokes an access token or refresh token at the ThaID Token Revoke Endpoint (<c>/api/v2/oauth2/revoke/</c>).
    /// </summary>
    /// <param name="token">The access token or refresh token to revoke.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>A <see cref="VerificationResult"/> containing the revocation response from ThaID.</returns>
    Task<VerificationResult> RevokeTokenAsync(
        string token,
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Retrieves citizen profile attributes from the ThaID UserInfo Endpoint (<c>/api/v2/oauth2/userinfo/</c>).
    /// </summary>
    /// <param name="accessToken">The valid Bearer access token.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>A <see cref="VerificationResult"/> containing the user profile attributes from ThaID.</returns>
    Task<VerificationResult> GetUserInfoAsync(
        string accessToken,
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Retrieves the OpenID Connect Discovery Configuration metadata from the ThaID Discovery Endpoint (<c>/.well-known/openid-configuration</c>).
    /// </summary>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>A <see cref="VerificationResult"/> containing the raw OpenID Configuration JSON keys.</returns>
    Task<VerificationResult> GetOpenIdConfigurationAsync(
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Retrieves the JSON Web Key Set (JWKS) public keys from the ThaID JWKS Endpoint (<c>/jwks/</c>).
    /// </summary>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>A <see cref="VerificationResult"/> containing the raw JWKS <c>keys</c> array.</returns>
    Task<VerificationResult> GetJwksAsync(
        CancellationToken cancellationToken = default);

    /// <summary>
    /// Validates and decodes an OIDC <c>id_token</c> JWT issued by ThaID (verifying <c>exp</c>, <c>iss</c>, <c>aud</c>, optional <c>nonce</c>, and cryptographic signature when JWKS keys are available).
    /// </summary>
    /// <param name="idToken">The JWT <c>id_token</c> returned by ThaID token exchange.</param>
    /// <param name="expectedNonce">Optional OIDC nonce expected in the token payload.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>A <see cref="VerificationResult"/> containing the decoded JWT claims in <see cref="VerificationResult.Data"/>.</returns>
    Task<VerificationResult> ValidateIdTokenAsync(
        string idToken,
        string? expectedNonce = null,
        CancellationToken cancellationToken = default);
}
